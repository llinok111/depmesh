#!/usr/bin/env node
'use strict';

/**
 * Write a Markdown analysis report for the bundled corpus.
 *
 * The numbers in the report are produced by the same code path the CLI and the
 * tests use, so a stale report is caught by `npm run depmesh:report -- --check`.
 */

const fs = require('node:fs');
const path = require('node:path');
const { analyse } = require('../lib/depmesh');
const { coverage } = require('../lib/depmesh/coverage');

const root = path.join(__dirname, '..');
const corpus = path.join(root, 'samples', 'vue-core', 'packages');
const tsConfig = path.join(root, 'samples', 'vue-core', 'tsconfig.json');
const outFile = path.join(root, 'docs', 'REPORT-vue-core.md');
const check = process.argv.includes('--check');

function main() {
  const analysis = analyse({ roots: [corpus], tsConfig, extensions: ['ts'] });
  const { graph, stats } = analysis;
  const cov = coverage(analysis.scan, graph);
  const cycles = graph.cycles();

  const lines = [];
  lines.push('# depmesh report - vuejs/core 3.5.44 (`packages/*/src`)');
  lines.push('');
  lines.push('Generated by `npm run depmesh:report`. The corpus is unmodified upstream');
  lines.push('source; see `samples/vue-core/PROVENANCE.md` for the pinned commit and checksum.');
  lines.push('');
  lines.push('## Totals');
  lines.push('');
  lines.push('| metric | value |');
  lines.push('| --- | --- |');
  lines.push(`| modules | ${stats.nodes} |`);
  lines.push(`| import edges | ${stats.edges} |`);
  lines.push(`| graph density | ${stats.density} |`);
  lines.push(`| entry points (no dependents) | ${stats.roots} |`);
  lines.push(`| leaves (no dependencies) | ${stats.leaves} |`);
  lines.push(`| cyclic components | ${stats.cycleComponents} |`);
  lines.push(`| modules inside a cycle | ${stats.cyclicNodes} |`);
  lines.push(`| external packages (not expanded) | ${stats.externals} |`);
  lines.push(`| unresolved imports | ${stats.unresolved} |`);
  lines.push('');
  lines.push('## Coverage of the analysis');
  lines.push('');
  lines.push('| metric | value |');
  lines.push('| --- | --- |');
  lines.push(`| files scanned | ${cov.files.discovered} |`);
  lines.push(`| parsed successfully | ${cov.files.parsed} |`);
  lines.push(`| failed to parse | ${cov.files.unparsed} |`);
  lines.push(`| specifiers extracted | ${cov.specifiers.total} |`);
  lines.push(`| resolved inside project | ${cov.specifiers.resolvedInternal} |`);
  lines.push(`| resolved to packages | ${cov.specifiers.resolvedExternal} |`);
  lines.push(`| unresolved | ${cov.specifiers.failed} |`);
  lines.push(`| internal resolution rate | ${(cov.specifiers.internalRatio * 100).toFixed(2)}% |`);
  lines.push('');
  if (cov.unresolved.findings.length) {
    lines.push('### Unresolved imports');
    lines.push('');
    for (const finding of cov.unresolved.findings) {
      lines.push(`- **${finding.reason}** (${finding.count}) - ${finding.label}`);
      for (const example of finding.examples.slice(0, 4)) {
        lines.push(`  - \`${example.file}\` -> \`${example.specifier}\``);
      }
    }
    lines.push('');
  }
  lines.push('## Cyclic components');
  lines.push('');
  lines.push('| # | modules | internal edges | shortest verified cycle |');
  lines.push('| --- | --- | --- | --- |');
  cycles.components.forEach((component, index) => {
    const sample = component.samples[0] ? component.samples[0].join(' -> ') : '';
    lines.push(`| ${index} | ${component.size} | ${component.internalEdges} | \`${sample}\` |`);
  });
  lines.push('');
  lines.push('Every cyclicity claim above is a strongly connected component computed by');
  lines.push("Tarjan's algorithm; every sample path is checked edge by edge against the");
  lines.push('real graph (`verified` flag in `depmesh cycles --json`).');
  lines.push('');
  lines.push('## Largest blast radii');
  lines.push('');
  const ranked = analysis.scan.nodes
    .map((node) => ({ id: node.id, blast: graph.impact(node.id).total }))
    .sort((a, b) => b.blast - a.blast || a.id.localeCompare(b.id))
    .slice(0, 10);
  lines.push('| module | transitive dependents |');
  lines.push('| --- | --- |');
  for (const row of ranked) lines.push(`| \`${row.id}\` | ${row.blast} |`);
  lines.push('');
  lines.push('## Limitations specific to this corpus');
  lines.push('');
  lines.push('- `@babel/types`, `@babel/parser`, `entities`, `estree-walker`, `magic-string` and');
  lines.push('  friends are declared by vue but not installed in this checkout, so their edges');
  lines.push('  are absent by construction (30 specifiers).');
  lines.push('- Test files (`__tests__`) are not part of the corpus; they are not counted.');
  lines.push('- `.ts` is the only extension scanned; `.json` and `.d.ts` imports are not nodes.');
  lines.push('');

  const text = `${lines.join('\n')}`;
  if (check) {
    // Git checks the file out with the platform's line ending (core.autocrlf),
    // so a byte comparison would report "stale" on Windows forever. Compare the
    // normalised content instead: the report is about numbers, not about CRLF.
    const normalise = (s) => s.replace(/\r\n/g, '\n');
    const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
    if (normalise(current) !== normalise(text)) {
      process.stderr.write(`${path.relative(root, outFile)} is stale - run npm run depmesh:report\n`);
      process.exitCode = 1;
      return;
    }
    process.stdout.write(`${path.relative(root, outFile)} is up to date\n`);
    return;
  }

  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, text);
  process.stdout.write(`wrote ${path.relative(root, outFile)} (${Buffer.byteLength(text)} bytes)\n`);
}

main();
